import type { Language } from "../i18n/translations";

export type LocalizedText = Record<Language, string>;

// Vraća tekst na izabranom jeziku (uz rezervu na srpski)
export const localized = (text: LocalizedText, lang: Language): string =>
  text[lang] ?? text.sr;

export interface Fountain {
  id: number;
  name: LocalizedText;
  // Koordinate su opcione: česma bez koordinata se ne prikazuje na mapi,
  // ali se prikazuje na stranicama "O česmama" i "Galerija"
  latitude?: number;
  longitude?: number;

  // Naslovna fotografija
  coverImage?: string;

  // Dodatne fotografije
  images?: string[];

  // Istorija i opis
  description: LocalizedText;

  shortDescription: LocalizedText;

  // Neutralni kodovi - prevode se pri prikazu
  status: "active" | "no_water";
  waterStatus?: "potable" | "no_water";
  profile?: FountainProfile;
}

export interface FountainProfile {
  totalDepth?: string;
  hydrogeologicalZone?: string;
  waterTemperature?: string;
  yearLabel?: LocalizedText;
  yearValue?: string;
  notes?: LocalizedText[];
  lithology?: [depthRange: string, material: string][];
}

